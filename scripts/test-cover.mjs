// Browser test for the Community Help Co cover letter builder against the live site (or BASE).
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
const BASE = process.argv[2] || 'https://communityhelp.com.au';
await mkdir('shots', { recursive: true });
const fails = [];
const ok = (c, m) => { console.log(`${c ? '✅' : '❌'} ${m}`); if (!c) fails.push(m); };
const browser = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch());
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, permissions: ['clipboard-read', 'clipboard-write'] });
const page = await ctx.newPage();
const errors = [], posts = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('request', (r) => { if (r.method() !== 'GET' && !/google-analytics|googletagmanager|analytics|\/cdn-cgi\/rum/.test(r.url())) posts.push(r.url()); });
await page.goto(`${BASE}/cover-letter-builder`, { waitUntil: 'networkidle' });
const pv = page.locator('[data-preview]');
await pv.locator('.cl-name').waitFor({ timeout: 15000 }).catch(() => {});
ok((await pv.textContent()).includes('Your name'), 'blank preview shows placeholder');
ok((await pv.textContent()).includes('Dear Hiring Manager'), 'no contact → "Dear Hiring Manager"');
await page.getByRole('button', { name: 'Fill with an example' }).click();
const t = await pv.textContent();
ok(t.includes('Dear Priya Shah') && t.includes('Retail Sales Assistant') && t.includes('Westside Outdoor Supplies'), 'example fills greeting, role and employer');
ok(t.includes('advertised on SEEK') && t.includes('I can start in two weeks'), 'source and start date flow into sentences');
await page.locator('[data-f="name"]').fill('Sam <b>Test</b>');
ok((await pv.locator('.cl-name').textContent()) === 'Sam <b>Test</b>', 'typed text shows as text (no HTML injection)');
await page.getByRole('button', { name: 'Copy the text' }).click();
const clip = await page.evaluate(() => navigator.clipboard.readText()).catch(() => '');
ok(clip.includes('Kind regards') && clip.includes('Re: Retail Sales Assistant'), 'copy gives the full plain-text letter');
await page.emulateMedia({ media: 'print' });
ok(!(await page.locator('.site-header').isVisible()) && (await pv.isVisible()) && !(await page.locator('.cl-form').isVisible()), 'print view shows only the letter');
await page.pdf({ path: 'shots/cover-letter.pdf', format: 'A4', printBackground: true });
await page.emulateMedia({ media: 'screen' });
await page.getByRole('button', { name: 'Clear everything' }).click();
ok((await pv.textContent()).includes('Your name'), 'clear empties the letter');
await page.reload({ waitUntil: 'networkidle' });
ok((await pv.textContent()).includes('Your name'), 'nothing stored after reload');
ok(posts.length === 0, `nothing typed is sent anywhere (${posts.length ? posts.join(', ') : 'none'})`);
ok(errors.length === 0, `no page errors${errors.length ? ': ' + errors.join(' | ') : ''}`);
const d = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await d.goto(`${BASE}/cover-letter-builder`, { waitUntil: 'networkidle' });
await d.getByRole('button', { name: 'Fill with an example' }).click();
await d.screenshot({ path: 'shots/cover-desktop.png' });
await browser.close();
console.log(fails.length ? `FAILED: ${fails.length}` : 'ALL PASSED');
process.exit(fails.length ? 1 : 0);
