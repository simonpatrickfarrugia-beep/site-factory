// Browser test for the Trade Admin quote/invoice builders and the job app calculator (BASE = site root).
import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
const BASE = (process.argv[2] || 'https://tradeadmin.com.au').replace(/\/$/, '');
await mkdir('shots', { recursive: true });
const fails = [];
const ok = (c, m) => { console.log(`${c ? '✅' : '❌'} ${m}`); if (!c) fails.push(m); };
const browser = await chromium.launch({ channel: 'chrome' }).catch(() => chromium.launch());
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const doc = () => page.locator('[data-doc]').innerText();

await page.goto(`${BASE}/quote-builder`, { waitUntil: 'networkidle' });
ok((await doc()).includes('QUOTE'), 'quote preview renders');
await page.fill('[name=bizName]', 'Bayside <b>Electrical</b>');
await page.fill('[name=abn]', '12 345 678 901');
await page.fill('[name=custName]', 'Sam Nguyen');
await page.locator('[data-f=d]').first().fill('Install 6 LED downlights');
await page.locator('[data-f=q]').first().fill('6');
await page.locator('[data-f=p]').first().fill('90');
await page.click('[data-add]');
await page.locator('[data-f=d]').nth(1).fill('Switchboard check');
await page.locator('[data-f=p]').nth(1).fill('150');
let t = await doc();
ok(t.includes('Bayside <b>Electrical</b>'), 'typed text shows as text (no HTML injection)');
ok(t.includes('$690.00') && t.includes('$69.00') && t.includes('$759.00'), 'GST added: 690 + 69 = 759');
await page.selectOption('[name=gst]', 'inc');
t = await doc();
ok(t.includes('$62.73') && t.includes('$690.00') && t.includes('Total price includes GST'), 'GST-inclusive: GST is 1/11 of 690 = 62.73');
await page.selectOption('[name=gst]', 'none');
t = await doc();
ok(!/GST \(10%\)/.test(t) && t.includes('No GST has been charged'), 'not registered: no GST line');
await page.selectOption('[name=gst]', 'ex');
ok((await page.locator('[data-warn] li').count()) === 0, 'no warnings once business, ABN and items are in');
await page.click('[data-convert]');
await page.waitForURL(/invoice-builder/);
await page.waitForTimeout(300);
t = await doc();
ok(t.includes('TAX INVOICE'), 'converted: registered business gets a TAX INVOICE');
ok(t.includes('Install 6 LED downlights') && t.includes('$759.00'), 'quote lines and totals carried into the invoice');
ok(t.includes('Due '), 'invoice shows a due date');
await page.locator('[data-f=p]').first().fill('200');
const warns = await page.locator('[data-warn] li').allInnerTexts();
await page.fill('[name=custName]', '');
await page.waitForTimeout(100);
const warns2 = await page.locator('[data-warn] li').allInnerTexts();
ok(warns2.some((w) => w.includes('$1,000')), 'warns when a $1,000+ tax invoice has no customer name or ABN');
await page.emulateMedia({ media: 'print' });
ok(!(await page.locator('.ta-form').isVisible()) && (await page.locator('[data-doc]').isVisible()), 'print view shows only the document');
await page.pdf({ path: 'shots/ta-invoice.pdf', format: 'A4', printBackground: true });
await page.emulateMedia({ media: 'screen' });

await page.goto(`${BASE}/job-management-software`, { waitUntil: 'networkidle' });
await page.fill('[data-people]', '1');
await page.fill('[data-jobs]', '20');
let first = await page.locator('[data-out] tr').first().innerText();
ok(/ServiceM8 Free/.test(first), `1 person, 20 jobs → ServiceM8 Free is cheapest (${first.split('\t')[0]})`);
await page.fill('[data-people]', '8');
await page.fill('[data-jobs]', '400');
first = await page.locator('[data-out] tr').first().innerText();
ok(/ServiceM8 Premium/.test(first), `8 people, 400 jobs → ServiceM8 Premium cheapest (${first.split('\t')[0]})`);
const tradifyLite = await page.locator('[data-out] tr', { hasText: 'Tradify Lite' }).innerText();
ok(tradifyLite.includes('$422'), `Tradify Lite for 8 = 8 × 48 × 1.1 = $422 (${tradifyLite.split('\t')[1]})`);
await page.screenshot({ path: 'shots/ta-calc.png', fullPage: false });
ok(errors.length === 0, `no page errors ${errors.join(' | ')}`);
await browser.close();
console.log(fails.length ? `FAILED: ${fails.length}` : 'ALL PASSED');
process.exit(fails.length ? 1 : 0);
